/* ------------------------------------------------------------------------ *
 * The Alto Adige plate
 *
 * The closest of the three tables, and the only one drawn at municipality
 * level: 282 comuni of Bolzano and Trento, from ISTAT boundaries via
 * geojson-italy (openpolis, CC-BY). At this scale a region outline would be
 * two blobs — the mosaic of comuni is what makes it read as home ground.
 *
 * Trento is in the drawing as well as Bolzano. The studio's work reaches Val
 * di Non, which is a Trentino valley, and a pin floating in the void just off
 * the bottom of a province outline looks like a bug rather than a fact.
 *
 * Same three steps as the other two plates: Mercator, Douglas-Peucker, and a
 * minimum area. The tolerance is the balance point measured against the size
 * the plate is actually drawn at: 0.55 gives 124 kB and detail nobody can see
 * at 560px tall, 1.6 gives 77 kB and starts rounding the valleys off. 1.1 is
 * 92 kB with the grain intact.
 *
 * Usage: node scripts/build-southtyrol-map.mjs <limits_IT_municipalities.geojson>
 * ------------------------------------------------------------------------ */

import fs from "node:fs";
import path from "node:path";

const SRC = process.argv[2];
const OUT = path.resolve("src/data/southtyrol.ts");
const URL_SRC =
  "https://raw.githubusercontent.com/openpolis/geojson-italy/master/geojson/limits_IT_municipalities.geojson";

/** Provinces kept, by ISTAT acronym. */
const PROVINCES = new Set(["BZ", "TN"]);

const W = 1000;
const TOL = 1.1;
const MIN_AREA = 3;

const merc = ([lon, lat]) => [
  (lon * Math.PI) / 180,
  Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360)),
];

function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const sq = tol * tol;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];

  while (stack.length) {
    const [a, b] = stack.pop();
    let far = -1;
    let best = 0;
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const dx = bx - ax;
    const dy = by - ay;
    const len = dx * dx + dy * dy;

    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      let t = len ? ((px - ax) * dx + (py - ay) * dy) / len : 0;
      t = t < 0 ? 0 : t > 1 ? 1 : t;
      const qx = ax + t * dx;
      const qy = ay + t * dy;
      const d = (px - qx) ** 2 + (py - qy) ** 2;
      if (d > best) {
        best = d;
        far = i;
      }
    }

    if (best > sq && far > 0) {
      keep[far] = 1;
      stack.push([a, far], [far, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const area = (ring) => {
  let a = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    a += ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
  }
  return Math.abs(a / 2);
};

const round = (n) => Math.round(n * 10) / 10;
const toPath = (ring) => `M${ring.map(([x, y]) => `${round(x)} ${round(y)}`).join("L")}Z`;

/* ------------------------------------------------------------------------ */

let geo;
if (SRC) {
  geo = JSON.parse(fs.readFileSync(SRC, "utf8"));
} else {
  process.stdout.write("fetching ISTAT municipalities (35 MB)…\n");
  const res = await fetch(URL_SRC);
  if (!res.ok) throw new Error(`source fetch failed: ${res.status}`);
  geo = await res.json();
}

const comuni = geo.features
  .filter((f) => PROVINCES.has(f.properties.prov_acr))
  .map((f) => {
    const polys =
      f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
    return {
      name: f.properties.name,
      prov: f.properties.prov_acr,
      rings: polys.map((poly) => poly[0].map(merc)),
    };
  });

if (!comuni.length) throw new Error("no municipalities matched — check prov_acr in the source");

let minX = Infinity;
let minY = Infinity;
let maxX = -Infinity;
let maxY = -Infinity;
for (const c of comuni) {
  for (const ring of c.rings) {
    for (const [x, y] of ring) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
}

const k = W / (maxX - minX);
const H = Math.round((maxY - minY) * k);
const place = ([x, y]) => [(x - minX) * k, (maxY - y) * k];

const out = comuni
  .map((c) => {
    const rings = c.rings
      .map((ring) => simplify(ring.map(place), TOL))
      .filter((ring) => ring.length > 3 && area(ring) > MIN_AREA)
      .sort((a, b) => area(b) - area(a));
    return { name: c.name, prov: c.prov, d: rings.map(toPath).join("") };
  })
  .filter((c) => c.d)
  .sort((a, b) => a.name.localeCompare(b.name));

const points = out.reduce((n, c) => n + (c.d.match(/L/g) || []).length, 0);

const body = `/* GENERATED BY scripts/build-southtyrol-map.mjs — do not edit by hand.
   ISTAT municipal boundaries via geojson-italy (openpolis, CC-BY).
   ${out.length} comuni of ${[...PROVINCES].join(" + ")}, ${points} points. */

export const viewBox = "0 0 ${W} ${H}";
export const mapW = ${W};
export const mapH = ${H};

/** The script's own projection, so runtime pins land where the drawing does. */
export function project(lon: number, lat: number): [number, number] {
  const x = (lon * Math.PI) / 180;
  const y = Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
  return [(x - ${minX}) * ${k}, (${maxY} - y) * ${k}];
}

export type Comune = { name: string; prov: string; d: string };

export const comuni: Comune[] = ${JSON.stringify(out, null, 0)
  .replace(/\},\{/g, "},\n  {")
  .replace(/^\[/, "[\n  ")
  .replace(/\]$/, ",\n]")};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body, "utf8");
console.log(
  `southtyrol.ts — ${out.length} comuni, ${points} points, ${(body.length / 1024).toFixed(1)} kB, viewBox 0 0 ${W} ${H}`,
);
